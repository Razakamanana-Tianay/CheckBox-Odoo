def test_vendor_core_matches_plugin_tree_verbatim():
    # The npm plugin runs the bundled CLI through whichever real python3/py/
    # python it finds on PATH; if the copy ever drifted from plugins/checkbox/
    # the package would ship broken code silently. Each vendored file must be
    # byte-identical to its source.
    package = build_adapters.build_opencode_package()
    vendored = [rel for rel in package if rel.startswith("opencode/vendor/")]
    assert vendored, "no vendored files produced"
    for rel in vendored:
        source = REPO_ROOT / "plugins" / "checkbox" / rel.removeprefix("opencode/vendor/")
        assert source.is_file(), f"{rel} has no source at {source}"
        assert source.read_text(encoding="utf-8") == package[rel], rel


def test_vendor_package_ships_launcher_and_ladder_rules():
    package = build_adapters.build_opencode_package()
    assert package["opencode/vendor/bin/checkbox"].startswith("#!/usr/bin/env python3")
    for rel in (
        "opencode/vendor/rules/ladder.md",
        "opencode/vendor/rules/ladder.compact.md",
        "opencode/vendor/rules/risk/18.0.json",
    ):
        assert rel in package


def test_check_rule_copies_detects_drift_in_vendored_file(tmp_path):
    build_adapters.main(["--output-dir", str(tmp_path)])
