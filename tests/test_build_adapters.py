"""Tests for scripts/build_adapters.py and scripts/check_rule_copies.py."""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import build_adapters  # noqa: E402
import check_rule_copies  # noqa: E402


def _rendered() -> dict[str, str]:
    return build_adapters.build()


def _doc_outputs() -> dict[str, str]:
    # The document adapters (AGENTS.md, per-host rules files, the opencode
    # README). The npm plugin package carries ladder text too, but its
    # machine files (package.json, TS sources, vendored Python/rules) are
    # exempt from the placeholder/header/guard-note invariants below.
    return {rel: renderer() for rel, renderer in build_adapters.OUTPUTS.items()}


def test_build_produces_every_declared_output():
    rendered = _rendered()
    assert set(rendered) == set(build_adapters.OUTPUTS) | set(
        build_adapters.build_opencode_package()
    )


def test_no_placeholder_survives_rendering():
    # A stray "{" means .format() silently left a placeholder unfilled, or a
    # neutral value itself contains a brace -- either is a real bug.
    for rel_path, content in _doc_outputs().items():
        assert "{" not in content, f"{rel_path} has an unrendered placeholder"
        assert "}" not in content, f"{rel_path} has an unrendered placeholder"


def test_generation_header_present_in_every_output():
    for rel_path, content in _doc_outputs().items():
        assert "Generated by scripts/build_adapters.py" in content, rel_path


def test_no_guard_note_present_in_every_output():
    # Every adapter must say it can't enforce the ladder -- non-negotiable
    # per adapters/CLAUDE.md: "no guard, no Stop check" must be stated.
    for rel_path, content in _doc_outputs().items():
        assert build_adapters.NO_GUARD_NOTE in content, rel_path


